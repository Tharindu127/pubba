// Writes lib/src/fold_table.dart: how each non-ASCII character reads after
// pubba's normalize (lowercase, NFKD, accents off, punctuation to spaces), taken
// from the JavaScript reference, since Dart has no Unicode normalization.
// Run from the repository root: node --experimental-strip-types packages/dart/tool/fold_table.ts
import { writeFileSync } from "node:fs";

const other = /[^a-z0-9+#.\s]/g;
const marks = /[̀-ͯ]/g;
const lines: string[] = [];
for (let c = 0x80; c <= 0x10ffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  const p = String.fromCodePoint(c).toLowerCase().normalize("NFKD").replace(marks, "").replace(other, " ");
  // Only white space reads as a space anyway, which is the default for a character not listed.
  if (/^\s+$/.test(p)) continue;
  const text = [...p].map((ch) => (/[a-z0-9+#. ]/.test(ch) ? ch : `\\u{${ch.codePointAt(0)!.toString(16)}}`)).join("");
  lines.push(`  0x${c.toString(16)}: '${text}',`);
}
const out = `// Generated by tool/fold_table.ts from the JavaScript reference (Unicode ${process.versions.unicode}). Do not edit.

/// Non-ASCII characters that don't read as a space after normalize: what they read as.
const Map<int, String> foldTable = {
${lines.join("\n")}
};
`;
writeFileSync(new URL("../lib/src/fold_table.dart", import.meta.url), out);
console.log(`${lines.length} characters written to lib/src/fold_table.dart`);
